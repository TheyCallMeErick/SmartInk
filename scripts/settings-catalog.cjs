'use strict';
// Run after build: extract the shipped settings forms in an isolated host double.
const fs = require('node:fs'),
  { setup, walk } = require('../tests/harness.cjs');
const routes = [
  ['page', 'Documento', 'openPagePanel'],
  ['interface', 'Interface e gestos', 'openInterface'],
  ['workflow', 'Atalhos e favoritos', 'openWorkflow'],
  ['preset-library', 'Biblioteca de pincéis', 'openPresetLibrary'],
  ['precision', 'Precisão e encaixes', 'openPrecision'],
  ['radial-settings', 'Menu radial', 'openRadialSettings'],
  ['device-profiles', 'Mesa digitalizadora', 'openDeviceProfiles'],
  ['navigation', 'Navegação e medidas', 'openNavigation'],
  ['brush', 'Pincel atual', 'openBrushPanel']
];
const out = [],
  label = (n) => (n.children?.length ? n.children.map(label).join(' ') : n.textContent || '');
for (const [kind, category, method] of routes) {
  const h = setup();
  try {
    h.view[method](...(kind === 'brush' ? ['write'] : []));
    for (const n of walk(h.view.flyout)) {
      if (!['BUTTON', 'LABEL', 'INPUT', 'SELECT', 'SUMMARY'].includes(n.tagName)) continue;
      if (['INPUT', 'SELECT'].includes(n.tagName) && !n.getAttribute('aria-label')) continue;
      const text = (
        n.getAttribute('aria-label') ||
        (n.tagName === 'LABEL'
          ? label(n.children.find((c) => c.tagName === 'SPAN') || n)
          : label(n))
      ).trim();
      if (
        text.length < 3 ||
        text.length > 160 ||
        /^←/.test(text) ||
        out.some((x) => x.kind === kind && x.label === text)
      )
        continue;
      out.push({ kind, category, label: text, ...(kind === 'brush' ? { brush: true } : {}) });
    }
  } finally {
    h.dispose();
  }
}
fs.writeFileSync(
  'src/features/settings-catalog.js',
  '/* Generated by scripts/settings-catalog.cjs from isolated forms. */\nconst SMART_INK_SETTINGS_CATALOG=' +
    JSON.stringify(out, null, 2) +
    ';\n'
);
console.log(out.length + ' settings entries');
